package org.sporotofpoorety.eternitymode.util;


import net.minecraft.entity.Entity;
import net.minecraft.util.math.MathHelper;
import net.minecraft.util.math.Vec3d;

import org.sporotofpoorety.eternitymode.util.OrthonormalBasis;
import org.sporotofpoorety.eternitymode.util.RotationParams;




public final class RotationUtil 
{

//Interpolate one direction towards another
    public static Vec3d rotateDirTowardsDir
    (
        Vec3d originalVec,
        Vec3d targetVec,
        double maxRotate   
    )
    {
//If directions are almost identical
        if (getAngleBetweenVecs(originalVec, targetVec) <= maxRotate)
        {
//Just snap to target
            return targetVec.normalize();
        }


//If not, get rotation parameters
        RotationParams rotParams = getRotationParams(originalVec, targetVec, maxRotate);
//Use them to perform rodrigues rotation
        return rotationRodrigues(originalVec.normalize(), rotParams);
    }




//Get angle between two vectors
    public static double getAngleBetweenVecs(Vec3d originalVec, Vec3d targetVec)
    {
//First normalize them
        Vec3d originalDir = originalVec.normalize();
        Vec3d targetDir  = targetVec.normalize();


//Get cos between the directions
        double cosBetweenDirs = originalDir.dotProduct(targetDir);
//Clamp cos to valid value
            cosBetweenDirs = MathHelper.clamp(cosBetweenDirs, -1.0D, 1.0D);
//Get angle (0 to π) of the cos (1 to -1)
        double angleBetweenDirs = Math.acos(cosBetweenDirs);


//Return angle between them
        return angleBetweenDirs;
    }




//Get parameters for a rotation
    public static RotationParams getRotationParams
    (
        Vec3d originalVec,
        Vec3d targetVec,
        double maxRotate   
    )
    {
//Normalize the directions
        Vec3d originalDir = originalVec.normalize();
        Vec3d targetDir  = targetVec.normalize();


//Get cross product of orig and tgt
        Vec3d dirsCrossProduct = originalDir.crossProduct(targetDir);

//Get and by default rotate around orig and trgt's perpendicular axis
        Vec3d axisForRotation = dirsCrossProduct.normalize();


//But if orig and trgt are practically opposite
        if (dirsCrossProduct.lengthSquared() < 0.001D)
        {
//Opposite = infinite possible rotations, 
//so i gotta pick an arbitrary perpendicular one
            Vec3d[] originalOrtho = OrthonormalBasis.makeOrthonormalBasis(originalDir);
//Arbitrarily pick original's ortho-right
            axisForRotation = originalOrtho[0];
        }


//Get cos and sin of rotation angle
        double cosOfRotation = Math.cos(maxRotate);
        double sinOfRotation = Math.sin(maxRotate);


//Return rotation parameters
        return new RotationParams(axisForRotation, cosOfRotation, sinOfRotation);
    }


    public static Vec3d rotationRodrigues(Vec3d originalDir, Vec3d axisForRotation, double rotRadians)
    {
        return rotationRodrigues(originalDir, new RotationParams(axisForRotation, Math.cos(rotRadians), Math.sin(rotRadians)));
    }

/*
Rodrigues rotation
    = Odir*cos0  +  (Ar X Odir)sin0  +  Ar(Odir * Ar)(1 - cos0)

Rotates vector around axis
*/
    public static Vec3d rotationRodrigues(Vec3d originalDir, RotationParams rotParams)
    {
//Get RotAxis  x  OrigDir
        Vec3d RotAxis_X_OrigDir  =  rotParams.axisForRotation.crossProduct(originalDir);
//Get RotAxis  *  OrigDir
        double OrigDir_Dot_RotAxis  =  rotParams.axisForRotation.dotProduct(originalDir);


//Original vec lowered by
//how much the rotation angle is
        Vec3d remainsOfOriginal  =  originalDir.scale(rotParams.cosOfRotation);


//Tangential force as generated by
//perpendicular direction scaled by sine of rotation
        Vec3d tangentialForce  =  RotAxis_X_OrigDir.scale(rotParams.sinOfRotation);


//When original vec was lowered,
//the part of it that was already 
//parallel to the axis of rotation got lowered too, so restore what was lost
        Vec3d parallelPartToRestore  =  rotParams.axisForRotation.scale(OrigDir_Dot_RotAxis).scale(1.0D - rotParams.cosOfRotation);


//Add all 3 components to get final interpolated dir
        Vec3d finalInterpolatedDir = 
            remainsOfOriginal
            .add(tangentialForce)
            .add(parallelPartToRestore);




//One last normalize just to be sure
        return finalInterpolatedDir.normalize();
    }


    public static void setEntityRotFromMotion(Entity entity)
    {
//Get horizontal speed
        float horizontalSpeed = MathHelper.sqrt(entity.motionX * entity.motionX + entity.motionZ * entity.motionZ);

//Set horz and vert rotation
        entity.rotationYaw = (float) (MathHelper.atan2(entity.motionX, entity.motionZ) * 360D / (2 * Math.PI));
        entity.rotationPitch = (float) (MathHelper.atan2(entity.motionY, (double) horizontalSpeed) * 360D / (2 * Math.PI));

//Rotation smoothing
        entity.rotationPitch = entity.prevRotationPitch + (entity.rotationPitch - entity.prevRotationPitch) * 0.2F;
        entity.rotationYaw = entity.prevRotationYaw + (entity.rotationYaw - entity.prevRotationYaw) * 0.2F;
    }


    public static void clampEntityPrevRot(Entity entity)
    {
        while (entity.rotationPitch - entity.prevRotationPitch < -180.0F)
        {
            entity.prevRotationPitch -= 360.0F;
        }

        while (entity.rotationPitch - entity.prevRotationPitch >= 180.0F)
        {
            entity.prevRotationPitch += 360.0F;
        }

        while (entity.rotationYaw - entity.prevRotationYaw < -180.0F)
        {
            entity.prevRotationYaw -= 360.0F;
        }

        while (entity.rotationYaw - entity.prevRotationYaw >= 180.0F)
        {
            entity.prevRotationYaw += 360.0F;
        }
    }

}
